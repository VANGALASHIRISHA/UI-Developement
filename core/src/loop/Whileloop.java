package loop;

public class Whileloop {

	public static void main(String[] args) {
		int i=1;
		while(i<=15)
		{
			System.out.println(i);
			i++;
		}
		int j=15;
		while(j>=1)
		{
			System.out.println(j);
			j--;
		}
		System.out.println("do while");
		int k=16;
		do
		{
			System.out.println(k);
			k++;
		}while(k<=15);

	}

}
