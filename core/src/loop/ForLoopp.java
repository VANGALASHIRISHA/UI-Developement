package loop;

public class ForLoopp {

	public static void main(String[] args) {
		int n=4;
		for(int i=1;i<=n;i++)
		{
			for(int j=1;j<=i;j++)
			{
				System.out.print(j+" ");
				
				
			}
			System.out.println();
			
		}
		System.out.println("Another Pattern");
		for(int i=1;i<=n;i++)
		{
			for(int j=1;j<=i;j++)
			{
				
				System.out.print(i+" ");
				
				
			}
			System.out.println();
			
		}
		System.out.println("Another Pattern");
		for(int i=1;i<=n;i++)
		{
			for(int j=1;j<=i;j++)
			{
				System.out.print("*"+" ");
				
				
			}
			System.out.println();
			
		}
		

		
	}

}
