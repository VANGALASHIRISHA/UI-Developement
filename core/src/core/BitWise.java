package core;

public class BitWise {

	public static void main(String[] args) {
		int a=5;
		int b=6;
		System.out.println(a&b);
		System.out.println(a|b);
		System.out.println(a^b);
		int m=24;
		int n=17;
		System.out.println(m&n);
		System.out.println(m|n);
		System.out.println(m^n);
		
		

	}

}
