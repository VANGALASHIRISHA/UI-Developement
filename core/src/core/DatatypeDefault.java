package core;

public class DatatypeDefault {
	byte b;				
	short sh;
	int it;
	long lt;
	char ch;
	float f;
	double d;
	boolean bn;
	public static void main (String[] args) {
		DatatypeDefault dtd=new DatatypeDefault();
		System.out.println("default value of byte= "+dtd.b);
		System.out.println("default value of short= "+dtd.sh);
		System.out.println("default value of int= "+dtd.it);
		System.out.println("default value of long= "+dtd.lt);
		System.out.println("default value of char= "+dtd.ch);
		System.out.println("default value of float= "+dtd.f);
		System.out.println("default value of double= "+dtd.d);
		System.out.println("default value of boolean= "+dtd.bn);
	}
	}

